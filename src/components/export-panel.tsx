"use client";

/**
 * CSV export panel (P4.5, contract rows 16–17).
 *
 * POST /export fires only when the pure canExport() helper says the machine's
 * EXPORT transition would pass (status APPROVED) — and the server still owns
 * the real gate (machine + live blocking re-check), so a stale click gets the
 * 409 rendered verbatim, never bypassed. The route intentionally has NO role
 * check (row 16), so the panel doesn't invent one.
 *
 * Download goes through GET /export/latest — the EXACT recorded bytes, with
 * the server's own filename/sha headers — so what a regulator downloads is
 * bit-identical to what was approved. Errors render verbatim.
 */
import { useRouter } from "next/navigation";
import { useState } from "react";
import { parseEnvelope } from "@/lib/envelope";
import { ErrorBanner } from "@/components/states";
import { canExport } from "@/lib/review";

export interface ExportRecordLite {
  id: string;
  fileName: string;
  formatVersion: string;
  csvSha256: string;
  createdAt: string;
}

export function ExportPanel({
  shipmentId,
  status,
  latestExport,
}: {
  shipmentId: string;
  status: string;
  latestExport: ExportRecordLite | null;
}) {
  const router = useRouter();
  const [record, setRecord] = useState<ExportRecordLite | null>(latestExport);
  const [error, setError] = useState<{ code?: string; message: string; details?: unknown } | null>(null);
  const [pending, setPending] = useState(false);
  const [downloading, setDownloading] = useState(false);

  async function generate() {
    setPending(true);
    setError(null);
    try {
      const res = await fetch(`/api/shipments/${shipmentId}/export`, {
        method: "POST",
        credentials: "same-origin",
      });
      const envelope = await parseEnvelope<{ exportRecord: ExportRecordLite }>(res);
      if (!envelope.ok) {
        setError({ code: envelope.error.code, message: envelope.error.message, details: envelope.error.details });
        return;
      }
      setRecord(envelope.data.exportRecord); // optimistic-but-verified: server's own row
      router.refresh(); // status → EXPORTED, header + read-only tables re-derive
    } catch {
      setError({ code: "NETWORK", message: "Could not reach the server. Try again." });
    } finally {
      setPending(false);
    }
  }

  async function download() {
    setDownloading(true);
    setError(null);
    try {
      const res = await fetch(`/api/shipments/${shipmentId}/export/latest`, { credentials: "same-origin" });
      if (!res.ok) {
        const envelope = await parseEnvelope(res);
        setError({ code: envelope.ok ? "DOWNLOAD" : envelope.error.code, message: envelope.ok ? "Download failed." : envelope.error.message });
        return;
      }
      // content-disposition is the server's filename contract (row 17).
      const disposition = res.headers.get("content-disposition") ?? "";
      const name = /filename="([^"]+)"/.exec(disposition)?.[1] ?? record?.fileName ?? "cargolens-export.csv";
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = name;
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(url), 10_000); // outlive the download start
    } catch {
      setError({ code: "NETWORK", message: "Could not reach the server. Try again." });
    } finally {
      setDownloading(false);
    }
  }

  return (
    <section className="rounded-lg border border-zinc-200 bg-white" aria-label="CSV export">
      <div className="border-b border-zinc-200 px-4 py-3">
        <h2 className="text-sm font-semibold text-zinc-900">CSV export</h2>
        <p className="mt-0.5 text-xs text-zinc-500">
          Filing layout <span className="font-mono">{record?.formatVersion ?? "cargolens-csv-v1"}</span> — generated by
          the same engine that passed the checks, gated by the machine.
        </p>
      </div>

      <div className="space-y-2 px-4 py-3 text-sm">
        {record ? (
          <dl className="space-y-1">
            <div className="flex justify-between gap-2 border-b border-dashed border-zinc-100 pb-1">
              <dt className="text-zinc-500">File</dt>
              <dd className="font-mono text-[13px] text-zinc-900">{record.fileName}</dd>
            </div>
            <div className="flex justify-between gap-2 border-b border-dashed border-zinc-100 pb-1">
              <dt className="text-zinc-500">SHA-256</dt>
              <dd className="max-w-[60%] truncate font-mono text-[13px] text-zinc-900" title={record.csvSha256}>
                {record.csvSha256}
              </dd>
            </div>
            <div className="flex justify-between gap-2 border-b border-dashed border-zinc-100 pb-1">
              <dt className="text-zinc-500">Generated</dt>
              <dd className="text-zinc-700">
                {new Date(record.createdAt).toLocaleString("en-GB", { timeZone: "Asia/Kolkata", hour12: false })} IST
              </dd>
            </div>
          </dl>
        ) : canExport(status) ? null : (
          <p className="text-xs text-zinc-500">
            Export unlocks when a manager approves this shipment — the machine's EXPORT event exists only from
            APPROVED, and the server re-verifies blocking checks at export time.
          </p>
        )}
      </div>

      {error ? (
        <div className="px-4 pb-3">
          <ErrorBanner code={error.code} message={error.message} details={error.details} />
        </div>
      ) : null}

      <div className="flex gap-2 px-4 pb-4">
        {canExport(status) ? (
          <button
            type="button"
            onClick={generate}
            disabled={pending}
            className="rounded-md bg-zinc-900 px-3 py-2 text-sm font-medium text-white hover:bg-zinc-800 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {pending ? "Generating…" : "Generate CSV export"}
          </button>
        ) : null}
        {record ? (
          <button
            type="button"
            onClick={download}
            disabled={downloading}
            className="rounded-md border border-zinc-300 bg-white px-3 py-2 text-sm font-medium text-zinc-700 hover:bg-zinc-50 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {downloading ? "Downloading…" : "Download CSV"}
          </button>
        ) : null}
      </div>
    </section>
  );
}
